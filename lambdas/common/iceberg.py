import os
import json
import logging
import random
import time
from collections import Counter
from collections.abc import Callable, Iterable
from datetime import date, datetime
from decimal import Decimal

import duckdb
from stripe import StripeObject

from common.fetched_object import FetchedObject

logger = logging.getLogger(__name__)

S3_TABLES = "s3_tables"
S3_TABLE_NAMESPACE = os.environ["s3_table_stripe_raw_namespace"]

REQUEST_WINDOW_METADATA_FIELDS = {
    "_requested_at": "TIMESTAMPTZ",
    "_received_at": "TIMESTAMPTZ"
}

TS_TZ = {"TIMESTAMPTZ", "TIMESTAMP WITH TIME ZONE"}
TS = {"TIMESTAMP", "TIMESTAMP WITHOUT TIME ZONE"}


def connect_s3_tables() -> duckdb.DuckDBPyConnection:
    """DuckDB connection with the iceberg catalog attached as s3_tables; authenticates with the AWS_* env credentials.

    Attaches the S3 table bucket (s3_table_bucket_arn), or, when iceberg_rest_endpoint is set, a plain Iceberg REST
    catalog whose data lives in the S3-compatible store at s3_endpoint (local docker, see tests/compose.yml).
    """
    e = os.environ
    con = duckdb.connect()
    # Extensions are pre-downloaded by layers/build.sh (Lambda: the duckdb-extensions layer in /opt) and autoload from
    # there on first use; not download at runtime for the performance reasons
    con.execute("SET home_directory = '/tmp'")  # only writable dir in Lambda
    con.execute(f"SET extension_directory = '{e['duckdb_extension_directory']}'")
    con.execute("SET autoinstall_known_extensions = false")

    # Lambda exposes the execution role credentials as env vars, so no aws extension / credential_chain needed
    # (httpfs + iceberg sign S3 and S3 Tables requests with SigV4 themselves)
    secret = [
        f"KEY_ID '{e['AWS_ACCESS_KEY_ID']}'",
        f"SECRET '{e['AWS_SECRET_ACCESS_KEY']}'",
        f"REGION '{e['AWS_REGION']}'",
    ]
    if "iceberg_rest_endpoint" in e:  # local
        scheme, host = e["s3_endpoint"].split("://")  # e.g. http://localhost:9090
        secret += [f"ENDPOINT '{host}'", "URL_STYLE 'path'", f"USE_SSL {scheme == 'https'}"]
        attach = (
            f"ATTACH '{e.get('iceberg_warehouse', '')}' AS {S3_TABLES} "
            f"(TYPE iceberg, ENDPOINT '{e['iceberg_rest_endpoint']}', AUTHORIZATION_TYPE 'none')"
        )
    else:  # S3 Tables
        secret.append(f"SESSION_TOKEN '{e['AWS_SESSION_TOKEN']}'")  # role credentials are always temporary
        attach = f"ATTACH '{e['s3_table_bucket_arn']}' AS {S3_TABLES} (TYPE iceberg, ENDPOINT_TYPE s3_tables)"

    con.execute(f"CREATE SECRET (TYPE s3, {', '.join(secret)})")  # before ATTACH, which already uses it
    con.execute(attach)
    return con


def load_iceberg_schema(table: str) -> dict:
    """Reads iceberg/{table}.json (generated by tools/stripe_to_iceberg, bundled into the Lambda zip) + metadata columns."""
    with open(f"iceberg/{table}.json") as f:
        return json.loads(f.read())


def target_table(table: str) -> str:
    return f'{S3_TABLES}.{S3_TABLE_NAMESPACE}."{table}"'


def create_table_if_not_exists(conn: duckdb.DuckDBPyConnection, table: str, schema: dict[str, str]) -> None:
    fields = "\n".join(f"   {field} {field_type}," for field, field_type in schema.items())

    # PARTITIONED BY (bucket(16, {iceberg_schema['created_at']}))
    DDL = f"""
    CREATE TABLE IF NOT EXISTS {target_table(table)} (
        {fields}
    )

     WITH (
            'format-version' = '3',
            'commit.retry.num-retries' = '0'
        );
    """
    try:
        conn.execute(DDL)
    except duckdb.Error as e:
        # IF NOT EXISTS is check-then-create: a concurrent writer can create the table in between (catalog 409)
        if "already exists" not in str(e):
            raise


STRING_TYPES = {"VARCHAR", "STRING", "TEXT"}


def source_expr(col_name: str, col_type: str) -> str:
    """Reads one column of the parsed row (r: struct of JSON values, see json_rows_source) as the schema's type.

    Rows go in as JSON text, not as Python dicts: DuckDB would infer one type for the whole batch from the dicts'
    values, so maps / variants of different shapes either fail the cast ({} vs {...}, str vs object) or get every
    other row's keys added with NULL values. Parsing each row's JSON keeps every value exactly as Stripe returned it.
    """
    t = col_type.strip().upper()
    value = f"r.{col_name}"  # JSON; SQL NULL when the key is missing
    text = f"({value}->>'$')"  # the value as text (unquoted string); NULL for JSON null too

    if col_name in REQUEST_WINDOW_METADATA_FIELDS:  # produced by us as ISO timestamps
        return f"{text}::{col_type} AS {col_name}"
    if t in TS_TZ:
        return f"to_timestamp({text}::BIGINT) AS {col_name}"  # epoch seconds -> instant
    if t in TS:
        return f"make_timestamp({text}::BIGINT * 1000000) AS {col_name}"  # epoch seconds -> naive UTC
    if t in STRING_TYPES:
        return f"{text} AS {col_name}"
    return f"{value}::{col_type} AS {col_name}"  # JSON value -> numbers, booleans, maps, variants, lists...


def json_rows_source(schema: dict[str, str]) -> str:
    """FROM clause turning $1 (list of JSON texts, see to_json) into one row each, r = struct of the schema's columns.

    json_transform parses each document once. Extracting every column with j->'$.col' instead would parse it once
    per column, which took ~2.1 GB for 5,000 Stripe subscriptions vs ~0.4 GB this way.
    """
    structure = json.dumps({c: "JSON" for c in schema})
    return f"(SELECT json_transform(unnest($1)::JSON, '{structure}') AS r)"


def build_merge(target: str, schema: dict[str, str], pk: str, extra_upsert_conditions: list[str] =[]) -> str:
    cols = list(schema)
    select_list = ",\n            ".join(source_expr(c, t) for c, t in schema.items())
    set_clause = ", ".join(f"{c} = source.{c}" for c in cols if c != pk)

    extra_upsert_condition = ""
    if extra_upsert_conditions:
        extra_upsert_condition = "\nAND " + " AND ".join(extra_upsert_conditions)


    return f"""
        MERGE INTO {target} AS target
        USING (
            SELECT {select_list}
            FROM {json_rows_source(schema)}
        ) AS source
        ON target.{pk} = source.{pk}
        WHEN MATCHED {extra_upsert_condition} THEN UPDATE SET {set_clause}
        WHEN NOT MATCHED THEN INSERT ({", ".join(cols)})
            VALUES ({", ".join(f"source.{c}" for c in cols)})
    """


# Applied by the MERGE too, as a safety net: within one transaction it sees the same snapshot as classify(), so it never
# rejects a row classify() let through (unless the lambdas' clocks are skewed)
UPDATE_GUARD = "source._requested_at >= target._received_at"


def to_row(fetched: FetchedObject, schema: dict[str, str]) -> dict:
    obj = fetched.obj
    d = (obj.to_dict() if isinstance(obj, StripeObject) else obj) | {"_requested_at": fetched.requested_at,
                                                                     "_received_at": fetched.received_at}
    return {c: d.get(c) for c in schema}


def _json_default(v):
    if isinstance(v, (datetime, date)):
        return v.isoformat()
    if isinstance(v, Decimal):  # the SDK parses Stripe's decimal strings (e.g. unit_amount_decimal); keep them as sent
        return str(v)
    raise TypeError(f"Can't serialize {type(v).__name__}: {v!r}")


def to_json(row: dict) -> str:
    """The row as the JSON text build_merge() reads its columns from (see source_expr)."""
    return json.dumps(row, default=_json_default)


def classify(conn: duckdb.DuckDBPyConnection, table: str, pk: str, pk_type: str, rows: list[dict]) -> dict[str, str]:
    """Compares each row's read window with the stored row's, returning {pk: action}:

    insert:  no stored row yet
    update:  our read started after the stored read finished -> ours is provably newer
    drop:    our read finished before the stored read started -> ours is provably older
    refetch: the windows overlap -> can't tell which read is newer, read the object from Stripe again
    """
    windows = [{"k": r[pk], "req": r["_requested_at"], "rec": r["_received_at"]} for r in rows]
    return dict(conn.execute(f"""
        SELECT source.k,
            CASE
                WHEN target.{pk} IS NULL                THEN 'insert'
                WHEN source.req >= target._received_at  THEN 'update'
                WHEN source.rec <= target._requested_at THEN 'drop'
                ELSE 'refetch'
            END
        FROM (SELECT s.k::{pk_type} AS k, s.req::TIMESTAMPTZ AS req, s.rec::TIMESTAMPTZ AS rec
              FROM (SELECT unnest($1) AS s)) AS source
        LEFT JOIN {target_table(table)} AS target ON target.{pk} = source.k
    """, [windows]).fetchall())


# Attempts of the whole classify -> refetch -> MERGE -> COMMIT unit when another writer committed in between.
# Retrying only the metadata commit would skip re-checking our decisions against the newer snapshot, which is what the
# catalog's own server-side retry does (apache/iceberg#18758), hence 'commit.retry.num-retries' = '0' on the tables
UPSERT_ATTEMPTS = 5
UPSERT_RETRY_BASE_DELAY_SECONDS = 0.2


def is_commit_conflict(e: Exception) -> bool:
    """The catalog rejected our commit because the table moved since our transaction's snapshot."""
    return isinstance(e, duckdb.TransactionException) and "409" in str(e)


def upsert(conn: duckdb.DuckDBPyConnection, table: str, objects: Iterable[FetchedObject],
           refetch: Callable[[str], FetchedObject]) -> Counter:
    """Creates the iceberg table from iceberg/{table}.json if missing and upserts every object that is not provably
    older than the stored one. Objects whose read window overlaps the stored one's are read again with refetch(pk).

    classify() and the MERGE run in one transaction, so both see the same snapshot. If another writer commits in
    between, COMMIT fails (409 from the catalog) and the whole transaction runs again on the newer snapshot.

    Returns the count of objects per action (insert / update / drop / refetch) of the attempt that committed, plus
    conflict_retries.
    """
    iceberg_schema = load_iceberg_schema(table)
    schema = iceberg_schema["schema"] | REQUEST_WINDOW_METADATA_FIELDS
    pk = iceberg_schema["primary_key"]
    create_table_if_not_exists(conn, table, schema)

    rows = {r[pk]: r for r in (to_row(o, schema) for o in objects)}
    if not rows:
        return Counter()

    for retry in range(UPSERT_ATTEMPTS):
        try:
            stats = upsert_in_transaction(conn, table, pk, schema, rows, refetch)
            stats["conflict_retries"] = retry
            return stats
        except Exception as e:
            if not is_commit_conflict(e) or retry == UPSERT_ATTEMPTS - 1:
                raise
            delay = UPSERT_RETRY_BASE_DELAY_SECONDS * 2 ** retry * random.uniform(0.5, 1.5)
            logger.warning("Commit conflict upserting %s (attempt %s/%s), retrying in %.2fs: %s",
                           table, retry + 1, UPSERT_ATTEMPTS, delay, e)
            time.sleep(delay)


def upsert_in_transaction(conn: duckdb.DuckDBPyConnection, table: str, pk: str, schema: dict[str, str],
                          rows: dict[str, dict], refetch: Callable[[str], FetchedObject]) -> Counter:
    """One attempt: classify -> refetch -> MERGE -> COMMIT in one transaction. Raises the catalog's 409 on COMMIT if
    another writer committed since this transaction's snapshot.

    Refetched rows replace their entries in rows, so a retry starts from those fresher reads instead of reading Stripe
    again for the same overlap.
    """
    stats = Counter()
    phase = _phase_logger(table, len(rows))
    conn.execute("BEGIN TRANSACTION")
    try:
        phase("classify")
        actions = classify(conn, table, pk, schema[pk], list(rows.values()))
        stats.update(actions.values())

        to_apply = [r for k, r in rows.items() if actions[k] in ("insert", "update")]

        phase("refetch")
        refetched = [to_row(refetch(k), schema) for k in rows if actions[k] == "refetch"]
        if refetched:
            # The new reads start after classify() saw the stored rows, so they must be provably newer now
            undecided = {k: a for k, a in classify(conn, table, pk, schema[pk], refetched).items()
                         if a not in ("insert", "update")}
            if undecided:
                raise RuntimeError(f"Refetched {table} objects are still not provably newer: {undecided}")
            rows.update((r[pk], r) for r in refetched)
            to_apply += refetched

        phase("merge")
        if to_apply:
            conn.execute(build_merge(target_table(table), schema, pk, [UPDATE_GUARD]), [[to_json(r) for r in to_apply]])
    except Exception:
        conn.execute("ROLLBACK")
        raise
    phase("commit")
    conn.execute("COMMIT")  # outside try: a failed COMMIT has already ended the transaction, ROLLBACK would fail too
    phase("done")

    return stats


def _phase_logger(table: str, rows: int) -> Callable[[str], None]:
    """Logs the start of each upsert phase with the time the previous one took, so a run that hangs or times out
    shows which phase it was in (the last line logged)."""
    last = {"name": None, "at": time.monotonic()}

    def phase(name: str) -> None:
        now = time.monotonic()
        took = f", {last['name']} took {now - last['at']:.2f}s" if last["name"] else ""
        logger.info("upsert %s (%s rows): %s%s", table, rows, name, took)
        last.update(name=name, at=now)

    return phase
